// ─── API pública ───────────────────────────────────────────────────────────────

/** Idioma activo */
let currentLang = 'es';

/** Devuelve el objeto de traducciones del idioma activo */
function t() {
  return LANGUAGES[currentLang] || LANGUAGES['es'];
}

/** Cambia el idioma activo y dispara el evento 'langChange' */
function setLanguage(langCode) {
  if (!LANGUAGES[langCode]) {
    console.warn(`translations.js: idioma '${langCode}' no encontrado. Se usará 'es'.`);
    langCode = 'es';
  }
  currentLang = langCode;
  try { localStorage.setItem('preferredLang', langCode); } catch(_) {}
  document.dispatchEvent(new CustomEvent('langChange', { detail: { lang: langCode } }));
}

/** Lista de idiomas disponibles para el selector */
function getAvailableLanguages() {
  return Object.entries(LANGUAGES).map(([code, data]) => ({
    code,
    name: data.meta.name,
    flag: data.meta.flag,
  }));
}

/** Inicializar con preferencia guardada o español */
(function initLang() {
  let saved = 'es';
  try { saved = localStorage.getItem('preferredLang') || 'es'; } catch(_) {}
  currentLang = LANGUAGES[saved] ? saved : 'es';
})();
